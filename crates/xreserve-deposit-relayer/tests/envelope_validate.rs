/// ACCEPT: exactly 65 bytes, returned byte-for-byte (`r‖s‖v` preserved, `v` carried).
#[test]
fn t_rly_06_accept_65_byte_attestation() {
    for v in att_vectors() {
        let sig = v.sig();
        let got = validate_attestation_envelope(&with_0x(&hex_of(&sig))).unwrap_or_else(|e| {
            panic!(
                "{}: a canonical 65-byte attestation must pass, got {e}",
                v.id
            )
        });
        assert_eq!(
            got, sig,
            "{}: returned bytes must be the exact wire bytes",
            v.id
        );
        assert_eq!(got[64], v.v_byte, "{}: v byte carried", v.id);
    }

    // and the bare (un-prefixed) hex form is accepted too
    let tv = test_vector();
    assert_eq!(
        validate_attestation_envelope(&hex_of(&tv.attestation())).expect("bare hex accepted"),
        tv.attestation()
    );
}

/// REJECT: any length other than 65 → `BadAttestationLength`, carrying the actual length.
/// 64 (the `v`-less form) and 66 are the two dangerous neighbours; 0/1/32 cover the degenerate ones.
#[rstest]
#[case::empty(0)]
#[case::one_byte(1)]
#[case::half(32)]
#[case::missing_v_byte(64)]
#[case::one_too_many(66)]
#[case::doubled(130)]
fn t_rly_06_reject_wrong_length_attestation(#[case] len: usize) {
    let bytes = vec![0x11; len];
    let err = validate_attestation_envelope(&with_0x(&hex_of(&bytes)))
        .expect_err("an attestation that is not 65 bytes must be rejected");

    assert_matches!(err, RelayerError::BadAttestationLength { actual } => {
        assert_eq!(actual, len, "the actual length must be carried");
    });
}

/// REJECT: malformed attestation hex → field-specific `MalformedHex` (not a length error), with the
